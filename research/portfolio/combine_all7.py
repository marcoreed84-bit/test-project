        ws.cell(row=r, column=6, value=f"=SUMIFS({pnl_rng},{sys_rng},A{r},{pnl_rng},\">0\")")
        ws.cell(row=r, column=7, value=f"=-SUMIFS({pnl_rng},{sys_rng},A{r},{pnl_rng},\"<0\")")
