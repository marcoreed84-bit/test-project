def build_workbook(window_start, window_end, window_label, out_path):
    portfolio = build_portfolio(window_start, window_end)
    all_systems = portfolio["all_systems"]
    ledger = make_ledger(all_systems)
    summary_rows, total = make_summary(all_systems)

    msg_start, msg_end = portfolio["msg_eff_start"], portfolio["msg_eff_end"]
    msg_data_start, msg_data_end = portfolio["msg_data_start"], portfolio["msg_data_end"]
    if msg_data_start > window_start or msg_data_end < window_end:
        msg_note = (f"MSG's real data does NOT cover this workbook's full requested window: within "
                    f"{window_start:%Y-%m-%d} .. {window_end:%Y-%m-%d}, MSG trades are only generated "
                    f"over its own real coverage, clipped to {msg_start:%Y-%m-%d %H:%M} .. "
                    f"{msg_end:%Y-%m-%d %H:%M} - a narrower span than the other six systems use in this "
                    f"same workbook. MSG's share of the combined totals below reflects that shorter real "
                    f"span, not a weaker strategy; it is not padded or extrapolated to cover the gap.")
    else:
        msg_note = (f"MSG's real data fully covers this workbook's window ({msg_data_start:%Y-%m-%d} .. "
                    f"{msg_data_end:%Y-%m-%d} spans {window_start:%Y-%m-%d} .. {window_end:%Y-%m-%d} "
                    f"completely) - no clipping was needed for MSG in this variant.")

    wb = Workbook()
    wb.remove(wb.active)
    ledger_last_row, ledger_header_row = write_trade_ledger_sheet(wb, ledger, window_label, window_start, window_end)
    write_summary_sheet(wb, all_systems, summary_rows, total, ledger_last_row, ledger_header_row, window_label)
    write_methodology_sheet(wb, dict(window_start=window_start, window_end=window_end,
                                      msg_data_start=msg_data_start, msg_data_end=msg_data_end,
                                      msg_note=msg_note), window_label)
    wb.save(out_path)

    return dict(all_systems=all_systems, ledger=ledger, summary_rows=summary_rows, total=total,
                msg_data_start=msg_data_start, msg_data_end=msg_data_end,
                msg_eff_start=msg_start, msg_eff_end=msg_end, out_path=out_path)


def _print_report(label, result):
    print(f"\n=== {label} ===")
    print(f"trades={result['total']['n']}  final_balance={STARTING_BALANCE + result['total']['net']:.2f}  "
          f"net_profit={result['total']['net']:.2f}  blended_pf={result['total']['pf']:.3f}  "
          f"win_rate={result['total']['win_rate']:.1f}%")
    for row in result["summary_rows"]:
        print(f"  {row['system']:14s} n={row['n']:5d}  net={row['net']:12.2f}  "
              f"pct={row['pct_of_total']:6.1f}%  win%={row['win_rate']:5.1f}  "
              f"pf={row['pf'] if row['pf'] != float('inf') else float('inf'):.3f}")
    print(f"  MSG data coverage: {result['msg_data_start']} .. {result['msg_data_end']}  "
          f"(used {result['msg_eff_start']} .. {result['msg_eff_end']} in this window)")
    print(f"  -> {result['out_path']}")


